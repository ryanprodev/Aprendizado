package A_Fundamentos;

public class TiposPrimitivos {
    static void main() {
        // 1. Número inteiro
        int idade = 18;
        // 2. Número com ponto flutuante(decimal)
        double altura = 1.75;
        // 3. Valor lógico (verdadeiro ou falso)
        boolean estudante = true;
        // 4. Um único caractere (Usando aspas simples)
        char sexo = 'M';

        // Imprimindo todos no console
        System.out.println("Idade: " + idade);
        System.out.println("Altura: " + altura);
        System.out.println("É estudante? " + estudante);
        System.out.println("Sexo: " + sexo);

    }
}
